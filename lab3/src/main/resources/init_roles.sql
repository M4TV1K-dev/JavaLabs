
CREATE USER shelter_service WITH PASSWORD 'shelter_pass';

GRANT CONNECT ON DATABASE shelter_db TO shelter_service;

GRANT USAGE ON SCHEMA public TO shelter_service;

GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA public TO shelter_service;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO shelter_service;

ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO shelter_service;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT USAGE, SELECT ON SEQUENCES TO shelter_service;
